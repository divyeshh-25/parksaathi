import { pool } from "../db.js";

const createTables = `
  CREATE TABLE IF NOT EXISTS residents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    mobile VARCHAR(20) NOT NULL,
    flat_number VARCHAR(50) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'active'
      CHECK (status IN ('active', 'inactive')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );

CREATE TABLE IF NOT EXISTS vehicles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id UUID NOT NULL UNIQUE,
  registration_number VARCHAR(30) NOT NULL UNIQUE,
  vehicle_type VARCHAR(50),
  model VARCHAR(100),
  resident_id BIGINT NOT NULL
    REFERENCES residents(id) ON DELETE RESTRICT,
  qr_token UUID NOT NULL UNIQUE,
  qr_status VARCHAR(20) NOT NULL DEFAULT 'active'
    CHECK (qr_status IN ('active', 'inactive')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

  CREATE TABLE IF NOT EXISTS privacy_settings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  privacy_mode BOOLEAN NOT NULL DEFAULT TRUE,
  show_vehicle_number BOOLEAN NOT NULL DEFAULT TRUE,
  show_owner_name BOOLEAN NOT NULL DEFAULT FALSE,
  show_flat_number BOOLEAN NOT NULL DEFAULT FALSE,
  show_owner_mobile BOOLEAN NOT NULL DEFAULT FALSE,
  allow_contact_requests BOOLEAN NOT NULL DEFAULT TRUE,
  allow_urgent_notifications BOOLEAN NOT NULL DEFAULT TRUE,
  allow_qr_scanning BOOLEAN NOT NULL DEFAULT TRUE,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT privacy_settings_singleton CHECK (id = 1)
);
  CREATE INDEX IF NOT EXISTS idx_vehicles_resident_id
    ON vehicles(resident_id);
`;

try {
  await pool.query(createTables);

  console.log("Database tables created successfully!");
  console.log("- residents");
  console.log("- vehicles");
  console.log("- privacy_settings");
} catch (error) {
  console.error("Database initialization failed:", error.message);
  process.exitCode = 1;
} finally {
  await pool.end();
}